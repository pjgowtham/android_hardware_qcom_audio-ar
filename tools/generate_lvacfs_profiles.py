"""Generate profile constants from an unmodified vendor lvacfs_params directory."""

import argparse
from pathlib import Path
import re


PROFILE_FILE = re.compile(r"^(?:LVACFS|LVIMFS)_Parameter_(.+)\.txt$", re.IGNORECASE)


def identifier(value):
    value = re.sub(r"[^A-Za-z0-9_]", "_", value)
    if value[0].isdigit():
        value = "config_" + value
    return value


def read_profiles(path):
    tokens = [line.split("//", 1)[0].strip() for line in path.read_text().splitlines()]
    tokens = [token for token in tokens if token]
    profiles = []
    ids = set()
    names = set()
    for value, filename in zip(tokens, tokens[1:]):
        match = PROFILE_FILE.fullmatch(Path(filename).name)
        if not match or not re.fullmatch(r"[0-9]+", value):
            continue
        profile_id = int(value)
        if profile_id in ids:
            raise ValueError(f"{path}: duplicate profile ID {profile_id}")
        # The table's ID is authoritative: blob fixups can change it without
        # renaming the parameter file.
        name = re.sub(r"(?:^|_)ID[0-9]+_", "_", match[1], flags=re.IGNORECASE)
        name = re.sub(r"^xxxx_", "", name.lstrip("_"), flags=re.IGNORECASE)
        name = identifier(name).upper()
        if name in names:
            name += f"_ID{profile_id}"
        if name in names:
            raise ValueError(f"{path}: duplicate constant {name}")
        ids.add(profile_id)
        names.add(name)
        profiles.append((name, profile_id, Path(filename).name))
    if not profiles:
        raise ValueError(f"{path}: no profile entries found")
    return profiles


def generate(directory):
    configurations = sorted(directory.rglob("LVACFS_Configuration.txt"))
    if not configurations:
        raise ValueError(f"{directory}: no LVACFS_Configuration.txt found")
    lines = [
        "// Generated by generate_lvacfs_profiles.py; do not edit.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "#pragma once",
    ]
    namespaces = set()
    for path in configurations:
        parent = path.parent.relative_to(directory)
        group = "_".join(parent.parts) or path.parent.name
        namespace = identifier(group).lower()
        if namespace in namespaces:
            raise ValueError(f"{path}: duplicate configuration namespace {namespace}")
        namespaces.add(namespace)
        lines.extend(["", f"namespace lvacfs::profiles::{namespace} {{", "", "enum Profile : int {"])
        for name, value, filename in read_profiles(path):
            lines.append(f"    {name} = {value},  // {filename}")
        lines.extend(["};", "", f"}}  // namespace lvacfs::profiles::{namespace}"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="vendor lvacfs_params directory")
    parser.add_argument("output", type=Path, help="generated header in the device tree")
    args = parser.parse_args()
    try:
        header = generate(args.directory)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    args.output.write_text(header)


if __name__ == "__main__":
    main()
